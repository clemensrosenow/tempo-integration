import { loadConfig } from '../src/config.js';
import { getAuthorizedClient } from '../src/google/auth.js';
import { calendar } from 'googleapis/build/src/apis/calendar/index.js';
import { DateTime } from 'luxon';
loadConfig();
const st = JSON.parse((await import('node:fs')).readFileSync('.tempo/state.json', 'utf8'));
const cal = calendar({ version: 'v3', auth: await getAuthorizedClient('sandbox', '.tempo') });
const days = Number(process.argv[2] ?? 1);
const items = (await cal.events.list({ calendarId: st.tempoCalendarId, timeMin: new Date().toISOString(), timeMax: new Date(Date.now() + days * 86400000).toISOString(), singleEvents: true, orderBy: 'startTime' })).data.items ?? [];
for (const e of items) console.log(DateTime.fromISO(e.start!.dateTime!).toFormat('ccc HH:mm'), e.summary, '—', e.description?.split('\n')[0]);
